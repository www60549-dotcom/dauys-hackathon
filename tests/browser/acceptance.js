    await page.getByRole('button',{name:'Вернуть в работу',exact:true}).click();
    await page.getByText('Версия карточки: 9',{exact:true}).waitFor();checks++;
    await page.getByRole('button',{name:'Закрыть диалог',exact:true}).click();
    await page.getByRole('button',{name:'Создать обращение',exact:true}).click();
    const refusalTitle='Автопроверка: комната отдыха '+Date.now();
