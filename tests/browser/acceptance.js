    await page.getByRole('heading',{name:'Карта проблем',exact:true}).waitFor();checks++;
    await page.getByRole('tab',{name:'Эффект и экономия',exact:true}).click();
    await page.getByRole('heading',{name:'Потенциальный эффект',exact:true}).waitFor();checks++;
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button',{name:/^Профиль:/}).click();
    await page.getByRole('button',{name:'QR-код для телефона',exact:true}).click();
    const qr=page.getByRole('img',{name:'QR-код ссылки на форму обращения'});await qr.waitFor();
    await page.addScriptTag({path:qrLibrary});
    const decoded=await qr.evaluate(async svg=>{
      const copy=svg.cloneNode(true);copy.setAttribute('width','400');copy.setAttribute('height','400');
      const img=new Image();img.src='data:image/svg+xml;charset=utf-8,'+encodeURIComponent(new XMLSerializer().serializeToString(copy));await img.decode();
      const canvas=document.createElement('canvas');canvas.width=400;canvas.height=400;const ctx=canvas.getContext('2d');ctx.drawImage(img,0,0,400,400);return window.jsQR(ctx.getImageData(0,0,400,400).data,400,400)?.data;
    });
