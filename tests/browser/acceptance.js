  await page.getByLabel('Добавить файл до 10 МиБ').setInputFiles(fixture);
  await page.getByRole('button',{name:'Прикрепить',exact:true}).click();
  const attachment=page.getByRole('link',{name:/preflight-proof.txt/});await attachment.waitFor();
